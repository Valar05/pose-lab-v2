import assert from 'node:assert/strict';
import {SerinGlideWaveController} from '../src/serin-glide-wave-system.mjs';
const c=new SerinGlideWaveController();
const step=(seconds,drive)=>{let result;for(let i=0;i<Math.round(seconds*120);i++)result=c.update(1/120,drive);return result;};
const idle=step(.8,0);
assert.equal(idle.poseBlend,0);assert.equal(idle.mode,'idle');
assert.equal(idle.sourceMode,0);assert.equal(idle.sourceSwitchCount,0);
assert.ok(idle.wavePhase>0,'puddle should move when idle');
const phase=idle.wavePhase;
let transitionFrames=[];
for(let i=0;i<180;i++){
 const s=c.update(1/120,1);
 transitionFrames.push(s);
}
const go=transitionFrames.at(-1);
assert.ok(go.wavePhase-phase>1.4*4*2*Math.PI,'glide puddle faster than lava lamp');
assert.ok(go.forwardLean>=7.5&&go.forwardLean<=8.7,'visible but restrained body bend');
assert.ok(go.crest>0.02,'bow wave present');
assert.equal(go.sourceMode,1,'rightward glide uses approved moving sprite');
assert.equal(go.sourceSwitchCount,1,'one forward source handoff');
assert.ok(transitionFrames.some(s=>s.shapeProgress>0.25&&s.shapeProgress<0.5),'geometry intermediate on entry');
assert.ok(transitionFrames.find(s=>s.sourceMode===1).shapeProgress>=0.58,'source cannot jump on input frame');
const phaseAtBrake=go.wavePhase;
const coast=step(.06,0);
assert.equal(coast.sourceMode,1,'braking begins on existing glide sprite');
assert.ok(coast.forwardLean>0&&coast.shapeProgress<go.shapeProgress,'body bends during exit');
let exit=[];
for(let i=0;i<500;i++)exit.push(c.update(1/120,0));
const stop=exit.at(-1);
assert.equal(stop.mode,'idle');assert.equal(stop.sourceMode,0);
assert.equal(stop.sourceSwitchCount,2,'single return from glide to idle');
const firstIdle=exit.find(s=>s.sourceMode===0);
assert.ok(firstIdle.shapeProgress<=0.42&&firstIdle.shapeProgress>0.05,'exit handoff occurs while deformation is active');
assert.ok(firstIdle.wavePhase>phaseAtBrake,'pool continues after switch');
assert.ok(exit.some(s=>s.sourceMode===1&&s.shapeProgress<0.6),'glide image deforms before exit swap');
assert.ok(stop.waveAmplitude>0,'puddle never freezes at idle');
assert.ok(stop.crest<go.crest,'crest settles');
let reverseFrames=[];
for(let i=0;i<180;i++)reverseFrames.push(c.update(1/120,-1));
const reverse=reverseFrames.at(-1);
assert.ok(reverse.velocity<0,'reverse moves backwards');
assert.equal(reverse.sourceMode,0,'reverse uses authored idle source, no mirror');
assert.equal(reverse.sourceSwitchCount,2,'no added source swaps in reverse');
assert.ok(reverse.reverseBend>3.5&&reverse.reverseBend<=4.51,'visible reverse sprite shape bend');
assert.ok(Math.abs(reverse.forwardLean)<0.02,'forward lean settles during reverse');
step(3,0);
const forwardAgain=step(1,1);
assert.equal(forwardAgain.sourceSwitchCount,3);
const immediateReverse=step(.5,-1);
assert.equal(immediateReverse.sourceMode,0,'reverse from forward glide makes ONE transition back to idle sprite');
assert.equal(immediateReverse.sourceSwitchCount,4,'no reverse source thrashing');
const finalStop=step(4,0);
assert.equal(finalStop.sourceMode,0);
assert.equal(finalStop.sourceSwitchCount,4);
const x=new SerinGlideWaveController(),y=new SerinGlideWaveController();
for(let i=0;i<720;i++){const drive=i<260?1:0;x.update(1/120,drive);y.update(1/120,drive);}
assert.deepEqual(x.getState(),y.getState(),'determinism');
assert.throws(()=>x.update(-1,0),/WAVE_INVALID_DELTA/);
console.log('SERIN_WAVE_START_STOP_CREST_AND_PHYSICS_PASS');
