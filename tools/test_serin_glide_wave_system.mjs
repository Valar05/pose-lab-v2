import assert from 'node:assert/strict';
import {SerinGlideWaveController} from '../src/serin-glide-wave-system.mjs';
const c=new SerinGlideWaveController();
const step=(seconds,drive)=>{let result;for(let i=0;i<Math.round(seconds*120);i++)result=c.update(1/120,drive);return result;};
const idle=step(.8,0);
assert.equal(idle.poseBlend,0);assert.equal(idle.mode,'idle');
assert.equal(idle.sourceMode,0);assert.equal(idle.sourceSwitchCount,0);
assert.ok(idle.wavePhase>0,'puddle should move when idle');
const phase=idle.wavePhase;
const go=step(1.4,1);
assert.ok(go.wavePhase-phase>1.4*4*2*Math.PI,'glide puddle must outrun lava lamp');
assert.ok(go.forwardLean>8,'forward torso lean');
assert.ok(go.crest>0.02,'bow-wave present during movement');
assert.ok(go.poseBlend>0.7,'moving pose authority');
assert.equal(go.sourceMode,1,'right input must select EXACT new glide PNG');
assert.equal(go.sourceSwitchCount,1,'rightward movement has one artwork handoff');
const coast=step(.12,0);
assert.ok(coast.velocity<go.velocity,'stop decelerates');
assert.ok(coast.waveAmplitude>0.006,'liquid still moves during braking');
assert.equal(coast.sourceMode,1,'braking never switches artwork prematurely');
const stop=step(5,0);
assert.equal(stop.mode,'idle');assert.equal(stop.poseBlend,0);assert.equal(stop.velocity,0);
assert.equal(stop.sourceMode,0,'idle endpoint uses front idle PNG');
assert.equal(stop.sourceSwitchCount,2,'single artwork transition at each endpoint');
assert.ok(stop.waveAmplitude>0,'ambient pool never freezes');
assert.ok(stop.crest<go.crest,'crest settles');
const reverse=step(1.5,-1);
assert.ok(reverse.velocity<0,'reverse moves backward in world space');
assert.equal(reverse.sourceMode,0,'reverse from idle does not summon glide sprite');
assert.equal(reverse.sourceSwitchCount,2,'reverse cannot repeat source swaps');
assert.ok(Math.abs(reverse.forwardLean)<0.03,'reverse does not pitch / bend the body');
const reverseStop=step(3.5,0);
assert.equal(reverseStop.sourceMode,0);
const forwardAgain=step(1.0,1);
assert.equal(forwardAgain.sourceSwitchCount,3);
const immediateReverse=step(1.3,-1);
assert.equal(immediateReverse.sourceMode,1,'reverse from glide retains same sprite without flipping');
assert.equal(immediateReverse.sourceSwitchCount,3,'reverse after glide cannot swap again');
const finalStop=step(4.5,0);
assert.equal(finalStop.sourceMode,0);
assert.equal(finalStop.sourceSwitchCount,4);
const x=new SerinGlideWaveController(),y=new SerinGlideWaveController();
for(let i=0;i<720;i++){const drive=i<260?1:0;x.update(1/120,drive);y.update(1/120,drive);}
assert.deepEqual(x.getState(),y.getState(),'determinism');
assert.throws(()=>x.update(-1,0),/WAVE_INVALID_DELTA/);
console.log('SERIN_WAVE_START_STOP_CREST_AND_PHYSICS_PASS');
